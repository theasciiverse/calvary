#!/usr/bin/env python3
"""Bake the ground tile table into data/tile_colors.tsv.

The terminal renderer cannot show the original 256x256 textures, so each ground
tile is drawn in the mean colour of its texture instead. Texture sources, first
hit wins: the golgotha-forever checkout's textures/ (jpg, then tga), then the
original golgotha-textures.tar.gz.

Levels name tiles by the `save_name` alias from the level .scm texture lists
when one is given (("seawateriron" (save_name "greecebridgeside")) is stored as
greecebridgeside), and levels without a texture name table refer to tiles only by
check_sum32 of that name. So every alias gets its own row, carrying the colour of
its texture file and the (wave T) / (block T) flags from the .scm entry.

Columns: name (original case, the checksum input), r, g, b, flags
(2 = wave/water, 4 = blocking, as in tile.h).

Usage: tools/tile_colors.py [references/Golgotha dir]  (needs Pillow)
"""
import glob
import io
import os
import re
import sys
import tarfile

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
REF = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "../../../references/Golgotha")
FORK = os.path.join(REF, "golgotha-forever")
OUT = os.path.join(HERE, "../data/tile_colors.tsv")

WAVE, BLOCK = 2, 4


def mean_rgb(img):
    r, g, b = img.convert("RGB").resize((1, 1), Image.Resampling.BOX).getpixel((0, 0))
    return r, g, b


# texture file stem (lowercase) -> (original stem, colour)
textures = {}
fork_textures = os.path.join(FORK, "textures")
for fname in sorted(os.listdir(fork_textures)):
    stem, ext = os.path.splitext(fname)
    if ext.lower() not in (".jpg", ".tga") or stem.lower() in textures:
        continue
    try:
        textures[stem.lower()] = (stem, mean_rgb(Image.open(os.path.join(fork_textures, fname))))
    except OSError as e:
        print(f"skip {fname}: {e}", file=sys.stderr)

with tarfile.open(os.path.join(REF, "golgotha-textures.tar.gz")) as tar:
    for m in tar:
        stem, ext = os.path.splitext(os.path.basename(m.name))
        if not m.isfile() or ext.lower() != ".jpg" or stem.lower() in textures:
            continue
        textures[stem.lower()] = (stem, mean_rgb(Image.open(io.BytesIO(tar.extractfile(m).read()))))

rows = {stem: (stem, rgb, 0) for stem, rgb in textures.values()}

# ("file" (prop value) (prop value) ...) entries from every level texture list
entry = re.compile(r'\(\s*"([^"]+)"((?:\s*\(\s*\w+\s+[^()]*\))+)\s*\)')
prop = re.compile(r'\(\s*(\w+)\s+([^()]*?)\s*\)')
aliases = 0
for scm in sorted(glob.glob(os.path.join(FORK, "*.scm")) + glob.glob(os.path.join(FORK, "scheme/*.scm"))):
    for name, props in entry.findall(open(scm, errors="replace").read()):
        tex = textures.get(name.lower())
        if not tex:
            continue
        p = dict(prop.findall(props))
        flags = (WAVE if p.get("wave") == "T" else 0) | (BLOCK if p.get("block") == "T" else 0)
        key = p.get("save_name", '"%s"' % name).strip('"')
        if key not in rows or rows[key][2] == 0:
            aliases += key != name
            rows[key] = (key, tex[1], flags)

with open(OUT, "w") as f:
    f.write("# name\tr\tg\tb\tflags  (generated by tools/tile_colors.py)\n")
    for key in sorted(rows, key=str.lower):
        name, (r, g, b), flags = rows[key]
        f.write(f"{name}\t{r}\t{g}\t{b}\t{flags}\n")
print(f"{len(textures)} textures, {aliases} aliases -> {os.path.normpath(OUT)}")
